import logging

from typing import Dict, Any, List, Tuple

from lib.gdrive import get_sheet_settings, get_table

from asset_classes.asset import Asset


class Bond(Asset):
    """Class representing a bond asset.
    """
    def __init__(
        self,
        bond_id: str,
        capital: float,
        interest_rate: float,
        maturity_date: str,
        currency: str,
    ):
        self.bond_id = bond_id
        self.capital = capital
        self.currency = currency
        self.interest_rate = interest_rate
        self.maturity_date = maturity_date
        self.payment_schedule: List[Dict[str, Any]] = []

    def get_income(self) -> Tuple[float, str]:
        """
        Returns the income generated by the asset.
        This method can be overridden by subclasses if needed.
        """
        print(f"{sum(d["amount"] for d in self.payment_schedule)}, {self.currency}")
        return sum(d["amount"] for d in self.payment_schedule), self.currency

    def get_current_value(self) -> Tuple[float, str]:
        """
        Returns the current value of the bond.
        This method can be overridden by subclasses if needed.
        """
        return self.capital, self.currency

    def __repr__(self):
        return f"Bond ID: {self.bond_id}, Name: {self.bond_id}, Face Value: {self.capital}, Interest Rate: {self.interest_rate}, Maturity Date: {self.maturity_date}"


def parse_bond(data: Dict[str, Any], sheet: str) -> Bond:
    """
    Function to parse account data from the provided data.

    :param data: List of lists containing the account data.
    :return: List of dictionaries with account information.
    """
    new_bond = Bond(
        bond_id=data["name"],
        currency=data["currency"],
        capital=float(data["capital"].replace(",", "")),
        interest_rate=float(data["interest"].replace("%", "")) / 100,
        maturity_date=data["maturity_date"],
    )
    payment_data = get_table(sheet, data["payment_schedule"])
    new_bond.payment_schedule = []
    for row in payment_data[1:]:
        payment = {"seq": row[0], "date": row[1], "amount": float(row[2].replace(",", "")), "paid": row[3]}
        logging.debug(f"Payment: {payment}")
        new_bond.payment_schedule.append(payment)

    return new_bond


def fetch_bond(sheet: str) -> Bond:
    data = get_sheet_settings(sheet)
    if "itype" not in data or data["itype"].lower() != "bond":
        raise ValueError("The first cell of the Summary sheet must be 'Type' and the")

    bond = parse_bond(data, sheet)

    return bond
